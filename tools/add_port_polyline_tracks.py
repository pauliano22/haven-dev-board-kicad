"""Add the copper traces the EasyEDA->KiCad port dropped.

EasyEDA stores multi-segment traces as POLY records on copper layers; the
port (extracted/gen_pcb.py) only converted POLY on the outline layer, so 61
real traces (some with arcs) never reached the KiCad board. Run once on a
board generated by the port. Usage:
  python3 tools/add_port_polyline_tracks.py <board.kicad_pcb> [arc_sign]
"""
import glob, json, math, os, sys
import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = glob.glob(os.path.join(HERE, "..", "extracted", "stock_openearable", "PCB", "*.epcb"))[0]
MM = 0.0254
LAYERS = {1: pcbnew.F_Cu, 2: pcbnew.B_Cu, 15: pcbnew.In1_Cu, 16: pcbnew.In2_Cu,
          17: pcbnew.In3_Cu, 18: pcbnew.In4_Cu}
ARC_SIGN = float(sys.argv[2]) if len(sys.argv) > 2 else 1.0

board = pcbnew.LoadBoard(sys.argv[1])
nets = board.GetNetsByName()


def pt(x, y):
    return pcbnew.VECTOR2I(pcbnew.FromMM(x * MM), pcbnew.FromMM(y * MM))


def arc_mid(sx, sy, ex, ey, angle):
    dx, dy = ex - sx, ey - sy
    c = math.hypot(dx, dy)
    mx, my = (sx + ex) / 2, (sy + ey) / 2
    th = math.radians(angle) * ARC_SIGN
    h = (c / 2) / math.tan(th / 2)
    cx, cy = mx - h * dy / c, my + h * dx / c
    a = th / 2
    vx, vy = sx - cx, sy - cy
    return cx + vx * math.cos(a) - vy * math.sin(a), cy + vx * math.sin(a) + vy * math.cos(a)


added = 0
for line in open(SRC):
    if not line.startswith('["POLY"'):
        continue
    d = json.loads(line)
    layer, net, width, path = d[4], d[3], d[5], d[6]
    if layer not in LAYERS or not net:
        continue
    netinfo = nets[net] if net in nets else None
    x, y = path[0], path[1]
    i = 2
    mode = None
    while i < len(path):
        tok = path[i]
        if tok in ("L", "ARC"):
            mode = tok
            i += 1
            continue
        if mode == "L":
            nx, ny = path[i], path[i + 1]
            t = pcbnew.PCB_TRACK(board)
            t.SetStart(pt(x, y)); t.SetEnd(pt(nx, ny))
            i += 2
        else:
            ang, nx, ny = path[i], path[i + 1], path[i + 2]
            t = pcbnew.PCB_ARC(board)
            mxp, myp = arc_mid(x, y, nx, ny, ang)
            t.SetStart(pt(x, y)); t.SetMid(pt(mxp, myp)); t.SetEnd(pt(nx, ny))
            i += 3
        t.SetWidth(pcbnew.FromMM(width * MM))
        t.SetLayer(LAYERS[layer])
        if netinfo:
            t.SetNet(netinfo)
        board.Add(t)
        added += 1
        x, y = nx, ny
pcbnew.SaveBoard(sys.argv[1], board)
print(f"added {added} segments/arcs")
